import { useEffect, useState } from 'react';
import { Download, ExternalLink, FolderArchive, Pencil, Search, Trash2, Upload } from 'lucide-react';
import type { Asset, AssetKind } from '@/types';
import { assetManager } from '@/services/asset-manager';
import { formatBytes } from '@/services/resources';
import { toZinoError } from '@/services/errors';
import { uiBridge } from '@/services/ui-bridge';
import { useApp } from '@/app/store';
import { AssetMedia, useAssetUrl } from '@/components/AssetMedia';
import { ThreeDViewer } from '@/components/ThreeDViewer';
import { Dialog, Empty, Segmented, useAsync } from '@/components/ui';

type Filter = 'all' | AssetKind;
type Sort = 'newest' | 'oldest' | 'name' | 'size';

function AssetDetail({ asset, onClose, onChanged }: { asset: Asset; onClose: () => void; onChanged: () => void }) {
  const url = useAssetUrl(asset);
  const openChat = useApp((s) => s.openChat);
  const [name, setName] = useState(asset.name);
  const [editing, setEditing] = useState(false);
  const fmt = asset.path.split('.').pop()?.toLowerCase();
  const meta = asset.metadata;
  const act = async (fn: () => Promise<unknown>, ok?: string) => { try { await fn(); if (ok) uiBridge.toast('success', ok); onChanged(); } catch (e) { uiBridge.toast('error', toZinoError(e).message); } };
  return (
    <Dialog wide title={editing ? 'Rename asset' : asset.name} onClose={onClose}>
      <div className="stack">
        {editing ? (
          <div className="row"><input className="input" autoFocus value={name} onChange={(e) => setName(e.target.value)} />
            <button className="btn primary" onClick={() => act(async () => { await assetManager.rename(asset.id, name); setEditing(false); }, 'Renamed')}>Save</button></div>
        ) : null}
        <div style={{ position: 'relative', height: 380, background: 'var(--surface-2)', borderRadius: 10, display: 'grid', placeItems: 'center', overflow: 'hidden' }}>
          {asset.kind === 'model3d' && url && (fmt === 'glb' || fmt === 'gltf' || fmt === 'obj') ? <ThreeDViewer url={url} format={fmt} />
            : asset.kind === 'video' && url ? <video src={url} controls playsInline style={{ maxWidth: '100%', maxHeight: '100%' }} />
              : asset.kind === 'image' || (asset.kind === 'export' && asset.mime.startsWith('image/')) ? (url && <img src={url} alt={asset.name} style={{ maxWidth: '100%', maxHeight: '100%', objectFit: 'contain' }} />)
                : <AssetMedia asset={asset} />}
        </div>
        <dl className="kv">
          <dt>Type</dt><dd>{asset.kind} · {asset.mime}</dd>
          <dt>Size</dt><dd>{formatBytes(asset.sizeBytes)}{asset.width ? ` · ${asset.width}×${asset.height}` : ''}{asset.durationSec ? ` · ${asset.durationSec}s` : ''}</dd>
          <dt>Created</dt><dd>{new Date(asset.createdAt).toLocaleString()}</dd>
          {typeof meta.engine === 'string' && <><dt>Generated by</dt><dd>{meta.engine}</dd></>}
          {typeof meta.prompt === 'string' && meta.prompt && <><dt>Prompt</dt><dd className="selectable">{meta.prompt}</dd></>}
          {typeof meta.negativePrompt === 'string' && meta.negativePrompt && <><dt>Negative</dt><dd>{meta.negativePrompt}</dd></>}
          {meta.seed !== undefined && meta.seed !== null && <><dt>Seed</dt><dd>{String(meta.seed)}</dd></>}
          {typeof meta.revisedPrompt === 'string' && <><dt>Revised prompt</dt><dd>{meta.revisedPrompt}</dd></>}
          {asset.parentAssetId && <><dt>Derived from</dt><dd className="mono tiny">{asset.parentAssetId} (original kept)</dd></>}
          <dt>Stored at</dt><dd className="mono tiny">{asset.path}</dd>
        </dl>
        <div className="row wrap">
          <button className="btn" onClick={() => act(() => assetManager.exportAsset(asset.id))}><Download size={15} /> Export</button>
          <button className="btn" onClick={() => setEditing(true)}><Pencil size={15} /> Rename</button>
          {asset.chatId && <button className="btn" onClick={() => { onClose(); openChat(asset.chatId!); }}><ExternalLink size={15} /> Open chat</button>}
          <span className="grow" />
          <button className="btn danger" onClick={async () => {
            const ok = await uiBridge.confirm({ title: `Delete "${asset.name}"?`, message: 'The file is permanently removed from this iPad. Chats that referenced it will show it as deleted.', confirmLabel: 'Delete', destructive: true });
            if (ok) await act(async () => { await assetManager.remove(asset.id); onClose(); }, 'Deleted');
          }}><Trash2 size={15} /> Delete</button>
        </div>
      </div>
    </Dialog>
  );
}

export function AssetsView() {
  const [filter, setFilter] = useState<Filter>('all');
  const [search, setSearch] = useState('');
  const [sort, setSort] = useState<Sort>('newest');
  const [tick, setTick] = useState(0);
  const [open, setOpen] = useState<Asset | null>(null);
  const pending = useApp((s) => s.pendingAssetId);
  const { data } = useAsync(() => assetManager.list({ kind: filter === 'all' ? undefined : filter, search }), [filter, search, tick]);
  useEffect(() => {
    if (!pending) return;
    void assetManager.get(pending).then((a) => { if (a) setOpen(a); });
    useApp.setState({ pendingAssetId: null });
  }, [pending]);
  const sorted = [...(data ?? [])].sort((a, b) => sort === 'newest' ? b.createdAt - a.createdAt : sort === 'oldest' ? a.createdAt - b.createdAt : sort === 'name' ? a.name.localeCompare(b.name) : b.sizeBytes - a.sizeBytes);
  const total = sorted.reduce((s, a) => s + a.sizeBytes, 0);
  return (
    <div className="page">
      <div className="page-header">
        <div><h1>Assets</h1><div className="subtitle">{sorted.length} items · {formatBytes(total)} · stored only on this iPad</div></div>
        <span className="spacer" />
        <button className="btn" onClick={async () => { try { await assetManager.importFromFiles('any'); setTick((t) => t + 1); } catch (e) { const err = toZinoError(e); if (err.code !== 'CANCELLED') uiBridge.toast('error', err.message); } }}><Upload size={16} /> Import</button>
      </div>
      <div className="row wrap" style={{ marginBottom: 16 }}>
        <Segmented value={filter} onChange={setFilter} options={[{ value: 'all', label: 'All' }, { value: 'image', label: 'Images' }, { value: 'model3d', label: '3D models' }, { value: 'video', label: 'Videos' }, { value: 'import', label: 'Imported' }, { value: 'export', label: 'Exports' }]} />
        <div className="row grow" style={{ minWidth: 200 }}><Search size={16} className="faint" /><input className="input" placeholder="Search names and prompts" value={search} onChange={(e) => setSearch(e.target.value)} /></div>
        <select className="select" style={{ width: 150 }} value={sort} onChange={(e) => setSort(e.target.value as Sort)}>
          <option value="newest">Newest first</option><option value="oldest">Oldest first</option><option value="name">Name</option><option value="size">Largest</option>
        </select>
      </div>
      {sorted.length === 0 ? <Empty icon={<FolderArchive size={40} />} title="No assets">Generated images, 3D models and videos appear here automatically.</Empty> : (
        <div className="gallery">
          {sorted.map((a) => (
            <div key={a.id} className="gallery-item" onClick={() => setOpen(a)}>
              <div className="media"><AssetMedia asset={a} /></div>
              <div className="caption"><div className="truncate">{a.name}</div><div className="tiny faint">{a.kind} · {formatBytes(a.sizeBytes)}</div></div>
            </div>
          ))}
        </div>
      )}
      {open && <AssetDetail asset={open} onClose={() => setOpen(null)} onChanged={() => setTick((t) => t + 1)} />}
    </div>
  );
}
