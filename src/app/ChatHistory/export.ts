import { assetsRepo, chatsRepo, contextRepo, messagesRepo, uid } from '@/database/repositories';
import { ZinoStorage } from '@/native';
import { ZinoError } from '@/services/errors';

/** Export a conversation (all original messages + summaries) as Markdown and open the share sheet. */
export async function exportChat(chatId: string) {
  const chat = await chatsRepo.get(chatId);
  if (!chat) throw new ZinoError('NOT_FOUND', 'Chat not found.');
  const messages = await messagesRepo.list(chatId);
  const summaries = await contextRepo.summaries(chatId);
  const lines = [`# ${chat.title}`, '', `Exported from ZinoAgent on ${new Date().toLocaleString()}`, ''];
  for (const m of messages) {
    if (m.role === 'system') continue;
    const who = m.role === 'user' ? 'You' : m.role === 'assistant' ? `Assistant${m.meta.model ? ` (${m.meta.model})` : ''}` : `Tool: ${m.toolName}`;
    lines.push(`## ${who} — ${new Date(m.createdAt).toLocaleString()}`, '', m.role === 'tool' ? '```json\n' + m.content + '\n```' : m.content, '');
    for (const a of m.attachments) lines.push(`_Attachment: ${a.name} (${a.kind})_`, '');
  }
  if (summaries.length) {
    lines.push('---', '', '## Context summaries (generated by SmartContextEngine)', '');
    summaries.forEach((s, i) => lines.push(`### Summary ${i + 1} (level ${s.level}, ${s.sourceMessageIds.length} messages)`, '', s.content, ''));
  }
  const safe = chat.title.replace(/[^\w\- ]+/g, '').trim().slice(0, 60) || 'conversation';
  const path = `exports/${safe}-${uid().slice(0, 6)}.md`;
  await ZinoStorage.writeText({ path, text: lines.join('\n') });
  const size = (await ZinoStorage.stat({ path })).size ?? 0;
  await assetsRepo.save({ id: uid(), kind: 'export', name: `${chat.title}.md`, path, mime: 'text/markdown', sizeBytes: size, width: null, height: null,
    durationSec: null, chatId, messageId: null, taskId: null, parentAssetId: null, metadata: { type: 'conversation' }, createdAt: Date.now() });
  await ZinoStorage.share({ path });
}
